import AppKit
import Foundation
import Testing
@testable import Tic

@Suite("UpdateChecker")
struct UpdateCheckerTests {
    @Test("detects newer versions numerically")
    func newer() {
        #expect(UpdateChecker.isNewer("0.6.0", than: "0.5.0"))
        #expect(UpdateChecker.isNewer("v0.6.0", than: "0.5.0"))
        #expect(UpdateChecker.isNewer("0.10.0", than: "0.9.0"))   // not lexical
        #expect(UpdateChecker.isNewer("1.0.1", than: "1.0"))
    }

    @Test("same, older, or unparseable is not an update")
    func notNewer() {
        #expect(!UpdateChecker.isNewer("0.5.0", than: "0.5.0"))
        #expect(!UpdateChecker.isNewer("1.0", than: "1.0.0"))
        #expect(!UpdateChecker.isNewer("0.4.9", than: "0.5.0"))
        #expect(!UpdateChecker.isNewer("garbage", than: "0.5.0"))
    }

    @Test("parses the releases list: newest published version, every release's notes, no drafts or betas")
    func parse() throws {
        let json = #"""
            [{"tag_name":"v0.9.1-beta","html_url":"https://x/b","body":"","published_at":null,"draft":false,"prerelease":true},
             {"tag_name":"v0.9.0","html_url":"https://github.com/kasvith/tic/releases/tag/v0.9.0",
              "body":"## [0.9.0] - 2026-11-02\n\n### Features\n\n- *(update)* Install updates from the menu bar\n",
              "published_at":"2026-11-02T10:00:00Z","draft":false,"prerelease":false},
             {"tag_name":"v1.0.0","html_url":"https://x/d","body":"","published_at":null,"draft":true,"prerelease":false},
             {"tag_name":"v0.10.0-never","html_url":"https://x/old","body":"","published_at":null,"draft":true,"prerelease":false},
             {"tag_name":"v0.8.0","html_url":"https://github.com/kasvith/tic/releases/tag/v0.8.0",
              "body":"## [0.8.0] - 2026-10-26\n\n### Bug Fixes\n\n- Fix it\n","published_at":"2026-10-26T18:04:29Z",
              "draft":false,"prerelease":false}]
            """#
        let release = try UpdateChecker.parse(Data(json.utf8))
        #expect(release.version == "0.9.0")
        #expect(release.url.absoluteString == "https://github.com/kasvith/tic/releases/tag/v0.9.0")
        #expect(release.notes.map(\.version) == ["0.9.0", "0.8.0"])
        #expect(release.notes[0].sections == [.init(title: "Features", items: ["Install updates from the menu bar"])])
        #expect(release.notes[0].date != nil)
        #expect(throws: (any Error).self) { try UpdateChecker.parse(Data("[]".utf8)) }
        #expect(throws: (any Error).self) { try UpdateChecker.parse(Data("{}".utf8)) }
    }

    @Test("release notes: git-cliff groups become sections, scopes are dropped, the rest is ignored")
    func releaseNotes() {
        let body = """
            ## [0.8.0] - 2026-10-26

            ### Features

            - *(reorder)* Ghost placeholder drag with parent indicator and grip

            ### Bug Fixes

            - *(editor)* Leave Return to the input method during IME composition
            - Unscoped `fix`

            <!-- generated by git-cliff -->
            """
        let notes = ReleaseNotes.parse(version: "0.8.0", date: nil, body: body)
        #expect(notes.sections == [
            .init(title: "Features", items: ["Ghost placeholder drag with parent indicator and grip"]),
            .init(title: "Bug Fixes", items: ["Leave Return to the input method during IME composition", "Unscoped `fix`"]),
        ])
        #expect(ReleaseNotes.parse(version: "1.0", date: nil, body: "").sections.isEmpty)
    }

    @Test("what's new covers every version after the installed one, newest first")
    func notesSince() {
        let notes = ["0.9.0", "0.8.1", "0.8.0", "0.7.0"].map { ReleaseNotes(version: $0, date: nil, sections: []) }
        let release = UpdateChecker.Release(version: "0.9.0", url: URL(string: "https://x")!, notes: notes)
        #expect(release.notes(since: "0.8.0").map(\.version) == ["0.9.0", "0.8.1"])
        #expect(release.notes(since: "0.9.0").isEmpty)
    }
}

/// The stateful side: menu item, dot, and banner bookkeeping, with GitHub and the notification
/// center stubbed out.
@Suite("UpdateChecker state")
@MainActor
struct UpdateCheckerStateTests {
    /// Banners the stubbed notifier "posted" (by version).
    final class Banners { var posted: [String] = [] }
    /// Restarts the stubbed installer asked for (the real one would quit the test runner).
    final class Restarts { var count = 0 }

    private nonisolated static let releasePage = URL(string: "https://github.com/kasvith/tic/releases/tag/v0.6.0")!

    private static func freshDefaults() -> UserDefaults {
        let name = "UpdateCheckerTests.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: name)!
        defaults.removePersistentDomain(forName: name)
        return defaults
    }

    private static func makeChecker(
        current: String? = "0.5.0", latest: String? = "0.6.0",
        defaults: UserDefaults = freshDefaults(), banners: Banners = Banners(),
        installer: @escaping @Sendable (UpdateChecker.Release) async throws -> Void = { _ in throw URLError(.cancelled) },
        restarts: Restarts = Restarts()
    ) -> UpdateChecker {
        UpdateChecker(
            currentVersion: current, defaults: defaults,
            fetch: {
                guard let latest else { throw URLError(.notConnectedToInternet) }
                return .init(version: latest, url: releasePage)
            },
            notify: { release, _ in banners.posted.append(release.version) },
            installer: installer,
            restart: { restarts.count += 1 }
        )
    }

    /// Polls (up to a second) until `done`, letting an Update Now's task run.
    private static func wait(until done: () -> Bool) async throws {
        for _ in 0..<100 where !done() { try await Task.sleep(for: .milliseconds(10)) }
    }

    @Test("Update Now shows Installing… in the menu, then restarts into the new version")
    func installSucceeds() async throws {
        let restarts = Restarts()
        let checker = Self.makeChecker(installer: { _ in try await Task.sleep(for: .milliseconds(50)) }, restarts: restarts)
        await checker.check()
        checker.install()
        #expect(checker.menuTitle == "Installing v0.6.0…")
        #expect(!checker.isUnseen)
        try await Self.wait { restarts.count > 0 }   // success keeps "Installing…" up until Tic quits
        #expect(restarts.count == 1)
    }

    @Test("a failed install says why, keeps the update on offer, and never restarts")
    func installFails() async throws {
        let restarts = Restarts()
        let checker = Self.makeChecker(installer: { _ in throw UpdateInstaller.Failure.checksumMismatch }, restarts: restarts)
        await checker.check()
        checker.install()
        try await Self.wait { checker.installState != .installing }
        #expect(checker.installState == .failed("The download didn't match its checksum."))
        #expect(checker.menuTitle == "Update Available: v0.6.0…")
        #expect(restarts.count == 0)
        checker.clearFailure()   // closing the window
        #expect(checker.installState == .idle)
    }

    @Test("a newer release sets the item and the dot, and posts one banner even across re-checks")
    func newerRelease() async {
        let banners = Banners()
        let checker = Self.makeChecker(banners: banners)
        await checker.check()
        #expect(checker.menuTitle == "Update Available: v0.6.0…")
        #expect(checker.isUnseen)
        #expect(banners.posted == ["0.6.0"])

        await checker.check()   // the daily re-check
        #expect(checker.menuTitle == "Update Available: v0.6.0…")
        #expect(banners.posted == ["0.6.0"])
    }

    @Test("up to date (or ahead) shows nothing")
    func upToDate() async {
        let banners = Banners()
        for latest in ["0.5.0", "0.4.0"] {
            let checker = Self.makeChecker(latest: latest, banners: banners)
            await checker.check()
            #expect(checker.menuTitle == nil)
            #expect(!checker.isUnseen)
        }
        #expect(banners.posted.isEmpty)
    }

    @Test("the banner is remembered per version across launches")
    func bannerOncePerVersion() async {
        let defaults = Self.freshDefaults()
        let banners = Banners()
        await Self.makeChecker(defaults: defaults, banners: banners).check()
        await Self.makeChecker(defaults: defaults, banners: banners).check()   // relaunch
        #expect(banners.posted == ["0.6.0"])
        await Self.makeChecker(latest: "0.7.0", defaults: defaults, banners: banners).check()
        #expect(banners.posted == ["0.6.0", "0.7.0"])
    }

    @Test("markSeen clears the dot, keeps the item, and is remembered across launches")
    func seen() async {
        let defaults = Self.freshDefaults()
        let checker = Self.makeChecker(defaults: defaults)
        await checker.check()
        checker.markSeen()
        #expect(!checker.isUnseen)
        #expect(checker.menuTitle != nil)

        let relaunched = Self.makeChecker(defaults: defaults)
        await relaunched.check()
        #expect(!relaunched.isUnseen)
        #expect(relaunched.menuTitle != nil)

        let newer = Self.makeChecker(latest: "0.7.0", defaults: defaults)   // a newer one re-dots
        await newer.check()
        #expect(newer.isUnseen)
    }

    @Test("closing a menu that showed the item counts as seen; other menus don't")
    func menuTracking() async throws {
        let checker = Self.makeChecker()
        await checker.check()
        #expect(checker.isUnseen)

        let other = NSMenu()
        other.addItem(withTitle: "Quit Tic", action: nil, keyEquivalent: "")
        NotificationCenter.default.post(name: NSMenu.didEndTrackingNotification, object: other)
        try await Task.sleep(for: .milliseconds(50))
        #expect(checker.isUnseen)

        let ours = NSMenu()
        ours.addItem(withTitle: checker.menuTitle!, action: nil, keyEquivalent: "")
        NotificationCenter.default.post(name: NSMenu.didEndTrackingNotification, object: ours)
        try await Task.sleep(for: .milliseconds(50))
        #expect(!checker.isUnseen)
    }

    @Test("a failed fetch is silent and leaves the last result alone")
    func fetchFailure() async {
        let banners = Banners()
        let checker = Self.makeChecker(latest: nil, banners: banners)
        await checker.check()
        #expect(checker.menuTitle == nil)
        #expect(!checker.isUnseen)
        #expect(banners.posted.isEmpty)
    }

    @Test("no bundle version (swift run) disables the check")
    func noBundleVersion() async {
        let banners = Banners()
        let checker = Self.makeChecker(current: nil, banners: banners)
        await checker.check()
        #expect(checker.menuTitle == nil)
        #expect(banners.posted.isEmpty)
    }
}
